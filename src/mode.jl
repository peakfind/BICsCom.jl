# functions for compute fields of modes corresponding to BICs

"""
    ModeField

Contain information of modes corresponding to BICs. 

# Fields
- `k::Float64`: the wavenumber
- `inn::Float64`: the dielectric constant inside the cylinders or air-holes
- `ext::Float64`: the dielectric constant outside the cylinders or air-holes
- `r::Float64`: the radius of the cylinders or air-holes
- `orders::Vector{Int64}`: the orders of Bessel functions and Neumann functions
- `coeffs::Matrix{Float64}`: the coefficients in the cylindrical expansion outside the cylinder, see [`get_coeff`](@ref)
- `expan_coeffs::Vector{ComplexF64}`: the coefficients before special functions
- `mode::Symbol`: the polarizations, supported types: `:te` or `:tm`
- `α::Float64`: the Bloch wavenumber, it is only nonzero for propagating BICs
"""
struct ModeField 
    k::Float64 
    inn::Float64
    ext::Float64
    r::Float64
    orders::Vector{Int64}
    coeffs::Matrix{Float64}
    expan_coeffs::Vector{ComplexF64}
    mode::Symbol
    α::Float64
end

"""
    compute_mode(sp::SamplingPoints, k, r, inn, ext, homo; α::Float64 = 0.0, mode::Symbol = :te, period::Float64 = 2π)

Compute the mode of a BIC at the wavenumber `k`.

# Arguments
- `sp`: the sampling points along the boundary of the square cell, generated by [`get_samplingpoints`](@ref)
- `k`: the wavenumber; it should be at (or very close to) the BIC frequency
- `r`: the radius of the cylinder (dielectric rod) or air hole
- `inn`: the dielectric constant inside the cylinder or air hole
- `ext`: the dielectric constant outside the cylinder or air hole
- `homo`: the dielectric constant of the homogeneous medium outside the periodic slab, used by the transparent boundary condition, see [`apply_tbc!`](@ref)

# Keyword Arguments
- `α`: the Bloch wavenumber, `α = 0` for standing BICs, `α ≠ 0` for propagating BICs
- `mode`: the polarization, `:te` or `:tm`, see [`get_coeff`](@ref)
- `period`: the period of the slab. It must equal the cell width of the square used to build `sp`

!!! note
    The phase of the mode is fixed by a symmetry gauge (see `_fix_phase!`):
    for `α = 0` (standing waves) the field is real; for `α ≠ 0` (propagating
    BICs) it satisfies `u(-x, y) = conj(u(x, y))`. Only the overall scale
    remains arbitrary — use [`normalize_field!`](@ref) after
    [`evaluate_field`](@ref) to fix it.

"""
function compute_mode(sp::SamplingPoints, k, r, inn, ext, homo; α::Float64 = 0.0, mode::Symbol = :te, period::Float64 = 2π)
    n = sp.n
    
    odrs = [j - 1 - 2n for j in 1:4n]

    cydc = build_cylinder_cache(4n, k, r, inn, ext)
    coef = get_coeff(4n, cydc, inn, ext, mode = mode)
    bydc = build_boundary_cache(sp, 4n, k, ext)
    Λ, A = assemble_dtn(sp, 4n, coef, bydc, k, ext; mode = mode, homo = homo)
    Δ = apply_bc(Λ, n; α = α, period = period)
    apply_tbc!(Δ, sp, k; α = α, homo = homo, period = period)
    
    evals, evecs = eigen(Δ)
    idx = argmin(abs.(evals))
    v = evecs[:, idx]
    
    # Reconstruct the Dirichlet data on 4 edges
    u = _reconstruct_dirichlet(v, n, α, period)
    
    # Fix the phase
    _fix_phase!(u, α, n)
    
    c = A \ u

    return ModeField(k, inn, ext, r, odrs, coef, c, mode, α)
end

"""
    _fix_phase!(u, α, n) -> u

Fix the arbitrary global phase of the boundary Dirichlet data `u` (4n values,
counterclockwise: bottom → left → top → right).

For `α = 0` (standing waves), time-reversal symmetry maps the mode to itself,
so the mode is real up to a phase.

For `α ≠ 0` (propagating BICs) the mode is genuinely complex, but the
composition of mirror reflection `x → -x` and conjugation maps the mode to
itself, so the gauge `u(-x, y) = conj(u(x, y))` exists.

Mirror pairs: the bottom and top edges are reversed in place; the left and
right edges are swapped and reversed (counted twice, once per edge — a uniform
reweighting of an edge block does not change `arg(a)`).

!!! note
    Both sums are *bilinear* (no conjugation) — `dot(u, u)` computes `Σ|uᵢ|²`, which is real and would always give `γ = 0`.

The gauge determines the phase only up to a sign (`γ` and `γ + π` are
equivalent); the sign is determined by requiring the dominant entry of `u` to be
positive real.
"""
function _fix_phase!(u, α, n)
    if α == 0.0
        a = sum(x -> x^2, u)
    else
        a = sum(i -> u[i] * u[n+1 - i], 1:n) +            # bottom
            2 * sum(i -> u[n + i] * u[4n+1 - i], 1:n) +   # left & right
            sum(i -> u[2n + i] * u[3n+1 - i], 1:n)        # top
    end

    γ = -angle(a)/2
    phase = cis(γ)
    u .*= phase

    i0 = argmax(abs.(u))
    real(u[i0]) < 0 && (u .*= -1)

    return u
end

function _reconstruct_dirichlet(v, n, α, period)
    e⁺ = iszero(α) ? one(eltype(v)) : exp(im * α * period) 
    u = similar(v, 4n)
    
    copyto!(u, 1,   v, 1,   n)   # bottom edge
    copyto!(u, n+1, v, n+1, n)   # left
    copyto!(u, 2n+1, v, 2n+1, n) # top

    for j in 1:n
        u[3n + j] = e⁺ * v[2n + 1 - j] # right edge: reverse mirror of left with Bloch phase
    end
    
    return u
end

"""
    evaluate_field(mf::ModeField, xs, ys)
    evaluate_field(mf::ModeField, sq::Square, xs, ys)

Evaluate the field of `mf` on the grid given by `xs` and `ys`; `xs` varies along
the rows of the returned matrix.

The first method evaluates the field in the central cell only, where the
expansion was fitted. `xs` must lie within that cell (`|x| ≤ semi`); for points
outside it, use the second method.

The second method evaluates the field with Bloch continuation: each point is
folded into the cell of `sq` and multiplied by `exp(im * α * L * m)`, the phase of its
cell (`L = 2 * sq.semi`). For `α = 0` this is the periodic repetition. The `Square`
must be the one that generated the sampling points used to build `mf`, i.e.
`period == 2 * sq.semi`.

!!! note
    The field inherits the phase convention fixed by [`compute_mode`](@ref):
    real for standing waves (`α = 0`), and `u(-x, y) = conj(u(x, y))` for
    propagating BICs. Only the overall scale remains arbitrary; see
    [`normalize_field!`](@ref).
"""
function evaluate_field(mf::ModeField, xs, ys)
    field = zeros(ComplexF64, length(xs), length(ys))
    ki = mf.k * sqrt(mf.inn)
    ke = mf.k * sqrt(mf.ext)
    trunc = length(mf.orders)
    
    @inbounds for j in eachindex(ys)
        y = ys[j]

        for i in eachindex(xs)
            x = xs[i]
            rd = sqrt(x^2 + y^2)
            θ = atan(y, x)
        
            val = zero(ComplexF64)

            if rd < mf.r 
                for t in 1:trunc 
                    val += mf.expan_coeffs[t] * besselj(mf.orders[t], ki * rd) * exp(im * mf.orders[t] * θ)
                end
            else
                for t in 1:trunc
                    radial = mf.coeffs[1, t] * besselj(mf.orders[t], ke * rd) + mf.coeffs[2, t] * bessely(mf.orders[t], ke * rd)
                    val += mf.expan_coeffs[t] * radial * exp(im * mf.orders[t] * θ)
                end
            end
        
            field[i, j] = val
        end
    end

    return field
end

function evaluate_field(mf::ModeField, sq::Square, xs, ys)
    L = 2 * sq.semi
    ms = round.(Int, (xs .- sq.center[1]) ./ L)
    field = evaluate_field(mf, xs .-ms .* L,ys)
    field .*= exp.(im * mf.α * L .* ms)

    return field
end

# post-processing utilities for plotting modes

"""
    normalize_field!(field) -> field

Normalize `field` to unit maximum modulus (max-norm), the usual convention for
comparing the fields of different modes.
"""
normalize_field!(field) = (field ./= maximum(abs, field); field)